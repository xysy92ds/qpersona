import { chromium } from 'playwright'
const browser = await chromium.launch({ executablePath: process.env.HOME + '/.cache/ms-playwright/chromium-1255/chrome-linux-arm64/chrome', args: ['--no-sandbox', '--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream'] })
const ctx = await browser.newContext({ viewport: { width: 402, height: 862 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, permissions: ['microphone'] })
const page = await ctx.newPage()
const errors = []
page.on('pageerror', (e) => errors.push(e.message))
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
await page.goto('http://127.0.0.1:5173/#/', { waitUntil: 'networkidle' })
await page.waitForTimeout(700)
const bootText = await page.locator('#app').innerText()
console.log('boot Q gone:', !bootText.includes('Q伴'), '| has 笺页:', bootText.includes('笺页') || (await page.locator('.nav').count()) > 0)
// about
await page.goto('http://127.0.0.1:5173/#/me', { waitUntil: 'networkidle' })
await page.waitForTimeout(500)
await page.getByText('关于 笺页', { exact: true }).click()
await page.waitForTimeout(400)
const about = await page.locator('.about').innerText()
console.log('about clean:', !about.includes('腾讯') && !about.includes('QQ'), '| logo:', await page.locator('.about__logo').innerText())
await page.screenshot({ path: '/tmp/qshots/150-about.png' })
await page.keyboard.press('Escape')
// add friend copy
await page.goto('http://127.0.0.1:5173/#/add', { waitUntil: 'networkidle' })
await page.waitForTimeout(400)
console.log('banner:', (await page.locator('.banner').innerText()).replace(/\n/g,' | ').slice(0,80))
// messages menu count
await page.goto('http://127.0.0.1:5173/#/', { waitUntil: 'networkidle' })
await page.waitForTimeout(400)
await page.locator('.plus').last().click()
await page.waitForTimeout(300)
console.log('menu items:', await page.locator('.menu-item').count())
await page.keyboard.press('Escape')
// call hangup
await page.waitForTimeout(300)
await page.locator('.conv').first().click()
await page.waitForTimeout(600)
await page.locator('[aria-label="语音通话"]').click()
await page.waitForTimeout(500)
console.log('call opened:', await page.locator('.call').count())
await page.locator('.call__ctrl--hangup').click()
await page.waitForTimeout(600)
console.log('hangup closed:', await page.locator('.call').count())
console.log('errors:', errors.length ? errors.join(' | ') : 'none')
await browser.close()
