import { chromium } from 'playwright'
const browser = await chromium.launch({ executablePath: process.env.HOME + '/.cache/ms-playwright/chromium-1255/chrome-linux-arm64/chrome', args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 402, height: 862 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })
const errors = []
page.on('pageerror', (e) => errors.push(e.message))
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
await page.goto('http://127.0.0.1:5173/#/cloud', { waitUntil: 'networkidle' })
await page.waitForTimeout(500)
const user='pz_'+Math.random().toString(36).slice(2,8)
await page.locator('.tab', { hasText: '注册' }).click()
await page.locator('input[placeholder*="3~20"]').fill(user)
await page.locator('input[type="password"]').fill('secret123')
await page.getByText('注册并同步', { exact: true }).click()
await page.waitForTimeout(3000)
await page.goto('http://127.0.0.1:5173/#/add?tab=plaza', { waitUntil: 'networkidle' })
await page.waitForTimeout(600)
await page.getByText('云端广场', { exact: true }).click()
await page.waitForTimeout(1000)
console.log('cloud cards:', await page.locator('.plaza-card').count())
await page.getByText('上传', { exact: true }).first().click()
await page.waitForTimeout(500)
console.log('upload rows:', await page.locator('.upload-row').count())
await page.locator('.upload-row').first().click()
await page.waitForTimeout(1500)
console.log('after upload cards:', await page.locator('.plaza-card').count())
await page.screenshot({ path: '/tmp/qshots/170-plaza-cloud.png' })
console.log('errors:', errors.length ? errors.join(' | ') : 'none')
await browser.close()
