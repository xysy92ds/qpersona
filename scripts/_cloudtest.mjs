import { chromium } from 'playwright'
const browser = await chromium.launch({ executablePath: process.env.HOME + '/.cache/ms-playwright/chromium-1255/chrome-linux-arm64/chrome', args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 402, height: 862 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })
const errors = []
page.on('pageerror', (e) => errors.push(e.message))
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
await page.goto('http://127.0.0.1:5173/#/cloud', { waitUntil: 'networkidle' })
await page.waitForTimeout(600)
const user = 'ui_' + Math.random().toString(36).slice(2, 8)
await page.locator('.tab', { hasText: '注册' }).click()
await page.locator('input[placeholder*="3~20"]').fill(user)
await page.locator('input[type="password"]').fill('secret123')
await page.getByText('注册并同步', { exact: true }).click()
await page.waitForTimeout(4000)
console.log('logged:', await page.locator('.hero__title').textContent())
console.log('result:', await page.locator('.row').nth(1).textContent())
const token = await page.evaluate(() => localStorage.getItem('jianyie.cloud.token'))
console.log('token stored:', !!token)
const res = await fetch('https://jianyie-api.jianyie.workers.dev/api/sync/pull?since=0', { headers: { Authorization: 'Bearer ' + token } })
const data = await res.json()
console.log('server items:', data.items?.length, 'kinds:', [...new Set((data.items||[]).map(i=>i.kind))].join(','))
await page.screenshot({ path: '/tmp/qshots/160-cloud.png' })
console.log('errors:', errors.length ? errors.join(' | ') : 'none')
await browser.close()
